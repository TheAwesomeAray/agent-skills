import type { RegisterItem } from "../types.ts";
import { sevRank } from "../util.ts";
import type { RegisterChange } from "./reconcile.ts";

const md = (s: string | undefined): string => (s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const shortType = (t: string): string => t.split("<")[0].split(".").pop() + (t.includes("<") ? t.slice(t.indexOf("<")) : "");
const loc = (i: RegisterItem): string => `\`${i.file}${i.line ? `:${i.line}` : ""}\``;
const title = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);

export interface RenderContext {
  runId?: string;
  commit?: string;
  ratings?: Record<string, string>;
  changes?: RegisterChange[];
}

export function renderTechDebt(items: RegisterItem[], ctx: RenderContext): string {
  const by = (status: string) => items.filter((i) => i.status === status);
  const sorted = (list: RegisterItem[]) =>
    [...list].sort((a, b) => sevRank(b.severity) - sevRank(a.severity) || a.principle.localeCompare(b.principle) || a.id.localeCompare(b.id));
  const open = sorted(items.filter((i) => i.status === "open" || i.status === "reopened"));
  const count = (list: RegisterItem[], sev: string) => list.filter((i) => i.severity === sev).length;
  const out: string[] = [];
  const L = (s = "") => out.push(s);

  L("# Technical debt register");
  L();
  L("Generated from `items/`, one JSON file per item. Do not edit this file; change items through the harness CLI (`claim`, `mark-fixed`, `accept`) or an analysis run.");
  L();
  L("| | |");
  L("|---|---|");
  if (ctx.runId) L(`| Last analysis | run \`${ctx.runId}\` at commit \`${ctx.commit?.slice(0, 7)}\` |`);
  if (ctx.ratings) L(`| Risk ratings | ${Object.entries(ctx.ratings).map(([k, v]) => `${k.toUpperCase()} ${v}`).join(", ")} |`);
  L(`| Open | ${open.length} (${count(open, "critical")} critical, ${count(open, "high")} high, ${count(open, "medium")} medium, ${count(open, "low")} low) |`);
  L(`| In progress | ${by("in-progress").length} |`);
  L(`| Fixed, pending verification | ${by("fixed-pending-verification").length} |`);
  L(`| Accepted | ${by("accepted").length} |`);
  L(`| Dismissed as false positives | ${by("dismissed").length} |`);
  L(`| Resolved | ${by("resolved").length} |`);
  L();

  L("## Open");
  L();
  if (open.length === 0) L("Nothing open.");
  else {
    L("| Id | Severity | Principle | Type | Issue | Location | Since |");
    L("|---|---|---|---|---|---|---|");
    for (const i of open)
      L(`| \`${i.id}\` | ${title(i.severity)}${i.status === "reopened" ? " (reopened)" : ""} | ${i.principle.toUpperCase()} | \`${md(shortType(i.type))}\` | ${md(i.criterion ? `${i.criterion}: ${i.details}` : i.title)} | ${loc(i)} | ${i.first_seen.run} |`);
  }
  L();

  const inProgress = sorted(by("in-progress"));
  if (inProgress.length > 0) {
    L("## In progress");
    L();
    L("| Id | Severity | Type | Claimed by | Branch | Since |");
    L("|---|---|---|---|---|---|");
    for (const i of inProgress) L(`| \`${i.id}\` | ${title(i.severity)} | \`${md(shortType(i.type))}\` | ${md(i.claim?.agent)} | \`${md(i.claim?.branch)}\` | ${i.claim?.at ?? ""} |`);
    L();
  }

  const pending = sorted(by("fixed-pending-verification"));
  if (pending.length > 0) {
    L("## Fixed, pending verification");
    L();
    L("The next analysis run resolves these if the finding is gone.");
    L();
    L("| Id | Severity | Type | Fix commit |");
    L("|---|---|---|---|");
    for (const i of pending) L(`| \`${i.id}\` | ${title(i.severity)} | \`${md(shortType(i.type))}\` | \`${i.fix?.commit.slice(0, 7) ?? ""}\` |`);
    L();
  }

  const accepted = sorted(by("accepted"));
  if (accepted.length > 0) {
    L("## Accepted");
    L();
    L("Real debt that was deliberately not scheduled.");
    L();
    L("| Id | Severity | Type | Issue | Reason |");
    L("|---|---|---|---|---|");
    for (const i of accepted) L(`| \`${i.id}\` | ${title(i.severity)} | \`${md(shortType(i.type))}\` | ${md(i.title)} | ${md(i.reason)} |`);
    L();
  }

  const resolvedNow = (ctx.changes ?? []).filter((c) => c.change === "propose-resolved");
  if (resolvedNow.length > 0) {
    L("## Resolved in the last run");
    L();
    for (const c of resolvedNow) L(`- \`${c.id}\` ${md(c.title)} on \`${md(shortType(c.type))}\`${c.note ? `: ${md(c.note)}` : ""}`);
    L();
  }
  return out.join("\n");
}
